"""Regex-правила для извлечения сущностей из текста судебного решения.

Изолированы от NER (Natasha) намеренно: это чистые `re`-паттерны без
какой-либо модели, поэтому их можно проверять независимо (см.
tests/test_patterns.py) без затрат на прогон полного NER-пайплайна.

Каждый паттерн кладёт итоговое значение в группу 1 — это единый контракт,
на который опирается и EntityExtractor, и тесты.
"""

import re

# ---------------------------------------------------------------------------
# Номер дела.
#
# Требуем явный маркер перед номером — «№», латинскую «N» (отдельным словом)
# или слово «дело/делу» — иначе строки вида «пункт 2-3 соглашения» или
# «срок 10-15/2024 рабочих дней» дают ложные совпадения: сама по себе
# конструкция «цифры-дефис-цифры[/год]» слишком похожа на что угодно.
#
# Формат номера покрывает:
#   - арбитражные суды:            А40-12345/2024, СИП-15/2024, Ф05-6789/26
#   - суды общей юрисдикции:       2-1234/2024, 2а-500/2024, 33-4567/2024
#   - Верховный Суд / кассация:    5-КГ24-15-К2, 41-УД23-11 (без дроби в конце)
# ---------------------------------------------------------------------------
_CASE_NUMBER_MARKER = r"(?:№\s*|(?<!\S)N(?=\s)\s*|\bдел[ауо]\s+)"
_CASE_NUMBER_TOKEN = r"[А-Яа-яЁё\d]+(?:-[А-Яа-яЁё\d]+)+(?:/\d{2,4})?"
CASE_NUMBER_PATTERN = re.compile(_CASE_NUMBER_MARKER + "(" + _CASE_NUMBER_TOKEN + ")", re.IGNORECASE)

# ---------------------------------------------------------------------------
# Суд.
#
# Регекс-модель судов в РФ фрагментирована по типам: единого грамматического
# правила «прилагательное + суд» недостаточно — иначе «в суд» или «Суд первой
# инстанции» (общий термин, не название) тоже совпали бы. Поэтому явно
# перечисляем поддерживаемые формы, а не одно общее правило.
# ---------------------------------------------------------------------------
_COURT_BRANCHES = [
    # Верховный Суд РФ
    r"Верховный\s+Суд\b(?:\s+Российской\s+Федерации)?",
    # Суд по интеллектуальным правам — единственный случай, где голое «Суд»
    # без предшествующего прилагательного всё же является именем собственным.
    r"Суд\s+по\s+интеллектуальным\s+правам\b",
    # Арбитражный суд + регион/город/округ
    r"Арбитражный\s+суд\b"
    r"(?:\s+(?:города|г\.)\s+[А-ЯЁ][а-яё]+"
    r"|\s+[А-ЯЁ][а-яё]+ой\s+области"
    r"|\s+[А-ЯЁ][а-яё]+ого\s+округа)?",
    # Арбитражный апелляционный суд — нумерация словом (Первый…Двадцать первый)
    r"(?:Первый|Второй|Третий|Четвёртый|Четвертый|Пятый|Шестой|Седьмой|Восьмой"
    r"|Девятый|Десятый|Одиннадцатый|Двенадцатый|Тринадцатый|Четырнадцатый"
    r"|Пятнадцатый|Шестнадцатый|Семнадцатый|Восемнадцатый|Девятнадцатый"
    r"|Двадцатый|Двадцать\s+первый)\s+арбитражный\s+апелляционный\s+суд\b",
    # Кассационный суд общей юрисдикции — нумерация словом (их 9 в РФ)
    r"(?:Первый|Второй|Третий|Четвёртый|Четвертый|Пятый|Шестой|Седьмой|Восьмой"
    r"|Девятый)\s+кассационный\s+суд\s+общей\s+юрисдикции\b",
    # Районный суд (+ «города X» / «г. X»)
    r"[А-ЯЁ][а-яё]+\s+районный\s+суд\b(?:\s+(?:города|г\.)\s+[А-ЯЁ][а-яё]+)?",
    # Городской суд
    r"[А-ЯЁ][а-яё]+\s+городской\s+суд\b",
    # Гарнизонный военный суд — числовой префикс (номер гарнизона) намеренно
    # не входит в захват: «235 гарнизонный военный суд» → «гарнизонный
    # военный суд», сам номер гарнизона не часть имени суда.
    r"гарнизонный\s+военный\s+суд\b",
]
COURT_PATTERN = re.compile("(" + "|".join(_COURT_BRANCHES) + ")", re.IGNORECASE)

# ---------------------------------------------------------------------------
# Судья.
#
# Маркер — любая словоформа «судья»: судьи (родительный), судья
# (именительный), судьёй/судьей (творительный, с «ё» и без). ФИО — фамилия
# (в т.ч. через дефис) + один-два инициала, с пробелом между ними или без.
# ---------------------------------------------------------------------------
_JUDGE_MARKER = r"суд(?:ьи|ья|ьёй|ьей)\s+"
_JUDGE_NAME = r"[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?\s+[А-ЯЁ]\.\s?[А-ЯЁ]\."
JUDGE_PATTERN = re.compile(_JUDGE_MARKER + "(" + _JUDGE_NAME + ")", re.IGNORECASE)

# ---------------------------------------------------------------------------
# Сумма иска.
#
# Разряды могут быть разделены одиночным пробелом («500 000», «1 234 567»),
# дробная часть — через запятую или точку. Маркер — «в размере»/«на сумму»,
# без него любое число в тексте (номер дома, статья кодекса и т.п.) стало бы
# ложным совпадением.
# ---------------------------------------------------------------------------
_AMOUNT_MARKER = r"(?:в размере|на сумму)\s+"
_AMOUNT_NUMBER = r"\d+(?: \d{3})*(?:[.,]\d+)?"
CLAIM_AMOUNT_PATTERN = re.compile(_AMOUNT_MARKER + "(" + _AMOUNT_NUMBER + ")", re.IGNORECASE)

LEGAL_PATTERNS: dict[str, re.Pattern[str]] = {
    "case_number": CASE_NUMBER_PATTERN,
    "court": COURT_PATTERN,
    "judge": JUDGE_PATTERN,
    "claim_amount": CLAIM_AMOUNT_PATTERN,
}
